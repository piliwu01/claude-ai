def get_keywords(theme: str) -> list[str]:
    """取得主題關鍵詞，課文用預設值，自訂主題用主題本身。"""
    return TEXT_KEYWORDS.get(theme, [theme])


def fill_template(template: str, theme: str, keyword: str) -> str:
    """將佔位符替換成實際內容。"""
    n = random.randint(2, 5)
    roles = ["甲", "乙", "丙", "丁"]
    return (template
            .replace("{主題}", theme)
            .replace("{關鍵詞}", keyword)
            .replace("{N}", str(n))
            .replace("{角色A}", roles[0])
            .replace("{角色B}", roles[1])
            .replace("{情境}", f"關於{theme}的謎題"))


def generate_puzzle(theme: str, puzzle_type: str) -> dict:
    """生成單一謎題，回傳 dict：{type, question, hint, answer_placeholder}。"""
    keywords = get_keywords(theme)
    keyword = random.choice(keywords)
    templates = PUZZLE_TEMPLATES.get(puzzle_type, [])
    if not templates:
        return {}
    template = random.choice(templates)
    question = fill_template(template, theme, keyword)
    return {
        "type": puzzle_type,
        "keyword": keyword,
        "question": question,
        "hint": f"提示：想想「{keyword}」在「{theme}」中的意義。",
        "answer": "（請教師填入正確答案）",
    }


def generate_story(theme: str) -> str:
    """生成故事背景。"""
    template = random.choice(STORY_TEMPLATES)
    return template.replace("{主題}", theme)


def generate_link() -> str:
    """生成關卡串接提示語。"""
    return random.choice(LINK_TEMPLATES)


def generate_game(theme: str, puzzle_types: list[str], num_stages: int = 3) -> dict:
    """
    生成完整遊戲。
    回傳 dict：{theme, story, stages: [{stage_num, puzzle, link}]}
    """
    story = generate_story(theme)
    stages = []
    selected_types = puzzle_types.copy()
    # 若選的類型不夠，允許重複
    while len(selected_types) < num_stages:
        selected_types += puzzle_types
    random.shuffle(selected_types)

    for i in range(num_stages):
        ptype = selected_types[i % len(selected_types)]
        puzzle = generate_puzzle(theme, ptype)
        link = generate_link() if i < num_stages - 1 else "恭喜！你已破解所有謎題，逃出密室！"
        stages.append({
            "stage_num": i + 1,
            "puzzle": puzzle,
            "link": link,
        })
    return {
        "theme": theme,
        "story": story,
        "stages": stages,
    }
